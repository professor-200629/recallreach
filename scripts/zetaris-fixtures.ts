// Generates the fictional source databases that a local Zetaris instance federates:
// three separately owned systems (distributor ERP, pharmacy stock, returns desk), each
// with its own native column names. Run: npm run zetaris:fixtures
import { mkdirSync, writeFileSync } from 'node:fs';
import { MISSING_40, SCENARIOS } from '../lib/recall/sample.ts';

type Row = (string | number)[];
const q = (v: string | number) => `'${String(v).replaceAll("'", "''")}'`;
// Ledger column order: event_id, shipment_id, type, from, to, product, manufacturer, batch, qty, unit, location, reference, occurred_at
const SYSTEMS = {
  distributor_dispatches: { db: 'recall_distributor', table: 'dispatches', columns: ['dispatch_id', 'consignment_ref', 'product_name', 'manufacturer_name', 'batch_no', 'qty', 'qty_unit', 'consignee', 'invoice_no', 'dispatched_at'], pick: (r: Row) => [r[0], r[1], r[5], r[6], r[7], r[8], r[9], r[10], r[11], r[12]] },
  pharmacy_stock_events: { db: 'recall_pharmacy', table: 'stock_events', columns: ['txn_id', 'consignment_ref', 'product_name', 'manufacturer_name', 'batch_no', 'from_status', 'to_status', 'qty', 'qty_unit', 'pharmacy_name', 'doc_ref', 'recorded_at'], pick: (r: Row) => [r[0], r[1], r[5], r[6], r[7], r[3], r[4], r[8], r[9], r[10], r[11], r[12]] },
  return_records: { db: 'recall_returns', table: 'return_notes', columns: ['rma_id', 'consignment_ref', 'product_name', 'manufacturer_name', 'batch_no', 'qty', 'qty_unit', 'returned_from', 'rma_ref', 'received_at'], pick: (r: Row) => [r[0], r[1], r[5], r[6], r[7], r[8], r[9], r[10], r[11], r[12]] },
} as const;

const out = ['-- GENERATED by scripts/zetaris-fixtures.ts. Fictional training data only.',
  '-- Columns are text on purpose: malformed values (2.5 pens, a timestamp without a timezone) reach RecallReach unchanged.',
  "-- Read-only login used by Zetaris. Change the password for anything beyond a local demo.",
  "CREATE ROLE recallreach_reader LOGIN PASSWORD 'recallreach-demo-only';", ''];
for (const [key, s] of Object.entries(SYSTEMS)) {
  const rows = Object.values(SCENARIOS).flatMap(sc => sc.sources.filter(src => src.key === key).flatMap(src => src.rows));
  out.push(`CREATE DATABASE ${s.db};`, `\\connect ${s.db}`,
    `CREATE TABLE ${s.table} (row_no serial PRIMARY KEY, ${s.columns.map(c => `${c} text`).join(', ')});`,
    ...rows.map(r => `INSERT INTO ${s.table} (${s.columns.join(', ')}) VALUES (${s.pick(r).map(q).join(', ')});`),
    `REVOKE ALL ON SCHEMA public FROM PUBLIC;`, `GRANT CONNECT ON DATABASE ${s.db} TO recallreach_reader;`, `GRANT USAGE ON SCHEMA public TO recallreach_reader;`, `GRANT SELECT ON ${s.table} TO recallreach_reader;`, `\\connect postgres`, '');
}
mkdirSync('integrations/zetaris/fixtures', { recursive: true });
writeFileSync('integrations/zetaris/fixtures/01-sources.sql', out.join('\n'));

// New evidence for the demo: the pharmacy system records the 40-bottle quarantine later.
const f = MISSING_40.followup!.rows[0];
writeFileSync('integrations/zetaris/fixtures/02-followup-quarantine.sql', [
  '-- Run during the demo to simulate the pharmacy system recording new, fictional evidence:',
  '--   docker compose -f integrations/zetaris/docker-compose.yml exec -T sources psql -U postgres -d recall_pharmacy < integrations/zetaris/fixtures/02-followup-quarantine.sql',
  `INSERT INTO stock_events (${SYSTEMS.pharmacy_stock_events.columns.join(', ')}) VALUES (${SYSTEMS.pharmacy_stock_events.pick(f).map(q).join(', ')});`, ''].join('\n'));
console.log('Wrote integrations/zetaris/fixtures/01-sources.sql and 02-followup-quarantine.sql');
